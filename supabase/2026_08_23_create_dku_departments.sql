create or replace function public.normalize_dku_department_name(input text)
returns text
language sql
immutable
as $$
  select regexp_replace(
    regexp_replace(
      regexp_replace(
        regexp_replace(coalesce(input, ''), '\s+', '', 'g'),
        '^(프리무스국제|경영경제|사회과학|과학기술|바이오융합|스포츠과학|공공인재|보건과학|음악·예술|음악예술|SW융합|외국어|문과|법과|공과|사범|예술|의과|간호|치과|약학)대학?',
        '',
        'g'
      ),
      '학과|학부|전공|\(야\)|（야）|야간|대학',
      '',
      'g'
    ),
    '[^가-힣a-zA-Z0-9]',
    '',
    'g'
  );
$$;

create table if not exists public.dku_departments (
  id bigserial primary key,
  campus text not null,
  college_name text not null,
  department_name text not null,
  official_full_name text not null,
  normalized_name text generated always as (
    public.normalize_dku_department_name(department_name)
  ) stored,
  normalized_full_name text generated always as (
    public.normalize_dku_department_name(official_full_name)
  ) stored,
  source text not null default '단국대학교 공식 홈페이지 학부 목록 이미지',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists idx_dku_departments_official_full_name
  on public.dku_departments (official_full_name);

create index if not exists idx_dku_departments_normalized_name
  on public.dku_departments (normalized_name);

