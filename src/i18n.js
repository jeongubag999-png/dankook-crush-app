export function translateText(value, language = activeLanguage) {
  if (language === "ko" || !value || !/[가-힣]/.test(value)) return value;
  const dictionary = dictionaries[language];
  const leading = value.match(/^\s*/)?.[0] || "";
  const trailing = value.match(/\s*$/)?.[0] || "";
  const core = value.trim();
  if (Object.prototype.hasOwnProperty.call(dictionary, core)) {
    return `${leading}${dictionary[core]}${trailing}`;
  }
  let translated = value;
  for (const key of orderedKeys) {
    if (translated.includes(key)) translated = translated.split(key).join(dictionary[key]);
  }
  translated = translated
    .replace(/(\d{4})년\s*(\d{1,2})월\s*(\d{1,2})일/g, (_, year, month, day) =>
      `${month}/${day}/${year}`
    )
    .replace(/(\d{4})년\s*(\d{1,2})월/g, (_, year, month) =>
      `${month}/${year}`
    )
    .replace(/(\d{1,2})월\s*(\d{1,2})일/g, (_, month, day) =>
      `${month}/${day}`
    )
    .replace(/(\d{4})년/g, "$1")
    .replace(/(\d[\d,]*)\s*개/g, "$1")
    .replace(/(\d[\d,]*)\s*명/g, "$1 people");
  return translated;
}

