// 도서관 열람실 좌석 배치도 (도서관 좌석배정 앱 화면을 옮긴 것, 2026-09-28 기준).
// 좌표는 픽셀이 아니라 "좌석 한 칸" 단위의 도식 좌표다: c = 가로 칸, r = 세로 칸.
// 책상 사이 통로는 빈 칸으로 표현한다. 번호가 빠지거나 겹치지 않았는지는
// scripts/check-library-layouts.mjs로 검사한다.

const range = (from, to) => {
  const step = from <= to ? 1 : -1;
  const list = [];
  for (let n = from; step > 0 ? n <= to : n >= to; n += step) list.push(n);
  return list;
};

// 세로 줄: (c, r)에서 아래로 from→to 번호를 차례로 놓는다.
const v = (c, r, from, to, extra = {}) =>
  range(from, to).map((n, i) => ({ n, c, r: r + i, ...extra }));

// 가로 줄: (c, r)에서 오른쪽으로 번호 목록을 차례로 놓는다.
const h = (c, r, numbers, extra = {}) =>
  numbers.map((n, i) => ({ n, c: c + i, r, ...extra }));

// 좌우 2열 책상: 왼쪽 열은 leftFrom→leftTo, 오른쪽 열은 rightFrom→rightTo (둘 다 위→아래).
const desk = (c, r, [leftFrom, leftTo], [rightFrom, rightTo]) => [
  ...v(c, r, leftFrom, leftTo),
  ...v(c + 1, r, rightFrom, rightTo),
];

